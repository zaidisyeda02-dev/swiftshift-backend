CREATE TABLE IF NOT EXISTS services (
  id VARCHAR(64) PRIMARY KEY,
  name VARCHAR(200) NOT NULL,
  short VARCHAR(200) NOT NULL,
  description TEXT NOT NULL,
  includes JSON NOT NULL,
  good_to_know TEXT NOT NULL,
  image VARCHAR(255) NOT NULL,
  gallery JSON NOT NULL,
  film VARCHAR(255) NOT NULL,
  poster VARCHAR(255) NOT NULL,
  focal VARCHAR(32) NOT NULL DEFAULT 'center 40%',
  sort_order INT NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS steps (
  id VARCHAR(64) PRIMARY KEY,
  number VARCHAR(4) NOT NULL,
  name VARCHAR(200) NOT NULL,
  short VARCHAR(200) NOT NULL,
  description TEXT NOT NULL,
  happens JSON NOT NULL,
  image VARCHAR(255) NOT NULL,
  related_service VARCHAR(64) NOT NULL,
  focal VARCHAR(32) NOT NULL DEFAULT 'center 40%',
  sort_order INT NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS quote_requests (
  id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  quote_number VARCHAR(16) UNIQUE,
  name VARCHAR(200) NOT NULL,
  phone VARCHAR(50) NOT NULL,
  moving_from VARCHAR(200) NOT NULL,
  moving_to VARCHAR(200) NOT NULL,
  moving_date DATE NOT NULL,
  service_id VARCHAR(64) NOT NULL,
  service_name VARCHAR(200) NOT NULL,
  status ENUM('New', 'Contacted', 'Quoted', 'Booked', 'Cancelled') NOT NULL DEFAULT 'New',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS subscribers (
  id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  email VARCHAR(200) NOT NULL UNIQUE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS messages (
  id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(200) NOT NULL,
  contact VARCHAR(200) NOT NULL DEFAULT '',
  message TEXT NOT NULL,
  status ENUM('New', 'Read', 'Replied') NOT NULL DEFAULT 'New',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS admins (
  id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  email VARCHAR(200) NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  salt VARCHAR(64) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS sessions (
  id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  token VARCHAR(128) NOT NULL UNIQUE,
  admin_id INT NOT NULL,
  expires_at DATETIME NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (admin_id) REFERENCES admins (id) ON DELETE CASCADE
);
